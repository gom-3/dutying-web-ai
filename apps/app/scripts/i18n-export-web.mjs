import {writeFileSync} from 'node:fs';
import {dirname} from 'node:path';
import {ensureDir, generatedResourcesPath, readCatalogRows, unflattenMessages} from './i18n-catalog-utils.mjs';

const LOCALES = ['ko', 'en', 'ja', 'zh', 'th'];
const WEB_PLATFORMS = new Set(['shared', 'web']);

function stringifyMessages(value) {
    return JSON.stringify(value, null, 4)
        .replace(/</g, '\\u003c')
        .replace(/\u2028/g, '\\u2028')
        .replace(/\u2029/g, '\\u2029');
}

const rows = readCatalogRows().filter((row) => WEB_PLATFORMS.has(row.platform));
const flatByLocale = Object.fromEntries(LOCALES.map((locale) => [locale, {}]));
const usedRuntimeKeys = new Map();
const errors = [];

for (const row of rows) {
    if (!row.runtimeKey) {
        errors.push(`${row.messageId || 'unknown'}: missing runtimeKey`);
        continue;
    }

    if (usedRuntimeKeys.has(row.runtimeKey)) {
        errors.push(`${row.messageId}: runtimeKey already exported by ${usedRuntimeKeys.get(row.runtimeKey)}`);
        continue;
    }

    usedRuntimeKeys.set(row.runtimeKey, row.messageId);

    for (const locale of LOCALES) {
        flatByLocale[locale][row.runtimeKey] = row[locale] ?? '';
    }
}

if (errors.length > 0) {
    console.error(JSON.stringify({errors}, null, 2));
    process.exit(1);
}

const messagesByLocale = Object.fromEntries(
    LOCALES.map((locale) => [locale, unflattenMessages(flatByLocale[locale])]),
);

const file = `/* eslint-disable */
// Generated by scripts/i18n-export-web.mjs. Edit apps/app/i18n/catalog/messages.csv instead.

export const ko = ${stringifyMessages(messagesByLocale.ko)};

export type TLocale = typeof ko;

export const en: TLocale = ${stringifyMessages(messagesByLocale.en)};

export const ja: TLocale = ${stringifyMessages(messagesByLocale.ja)};

export const zh: TLocale = ${stringifyMessages(messagesByLocale.zh)};

export const th: TLocale = ${stringifyMessages(messagesByLocale.th)};

export const resources = {
    ko: {translation: ko},
    en: {translation: en},
    ja: {translation: ja},
    zh: {translation: zh},
    th: {translation: th},
} as const;
`;

ensureDir(dirname(generatedResourcesPath));
writeFileSync(generatedResourcesPath, file);

console.log(
    JSON.stringify(
        {
            generatedResourcesPath,
            messages: rows.length,
            locales: LOCALES,
        },
        null,
        2,
    ),
);
